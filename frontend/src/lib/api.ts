/**
 * CareSync Resilient API Client
 *
 * Communicates with the FastAPI backend when available.
 * If deployed on static hosts (like Vercel) without a live backend connection,
 * it automatically falls back to the deterministic client-side engine to guarantee
 * zero crashes and full interactivity.
 */

import {
  ExplainResponse,
  HealthStatus,
  HospitalOperationalSnapshot,
  SimulationScenarioResult,
} from '../types';
import { BASELINE_SNAPSHOT } from './mockData';

export function getActiveApiBase(): string {
  // Check user-configured override in localStorage
  if (typeof window !== 'undefined') {
    const custom = localStorage.getItem('caresync_custom_api_url');
    if (custom) return custom.replace(/\/+$/, '');
  }

  // Check build-time environment variable
  const envUrl = import.meta.env.VITE_API_BASE_URL as string | undefined;
  if (envUrl) return envUrl.replace(/\/+$/, '');

  return '/api';
}

export function setActiveApiBase(url: string | null): void {
  if (typeof window === 'undefined') return;
  if (!url || url.trim() === '') {
    localStorage.removeItem('caresync_custom_api_url');
  } else {
    localStorage.setItem('caresync_custom_api_url', url.trim());
  }
}

/**
 * Safely fetches and parses JSON, detecting if the server returned HTML
 * (such as Vercel's SPA index.html fallback) instead of valid JSON.
 */
async function safeFetchJson<T>(url: string, options?: RequestInit): Promise<T | null> {
  try {
    const res = await fetch(url, options);
    if (!res.ok) return null;

    const contentType = res.headers.get('content-type') || '';
    if (!contentType.includes('application/json')) {
      // Returned HTML or text instead of JSON (common on Vercel SPA rewrites)
      return null;
    }

    return await res.json();
  } catch {
    return null;
  }
}

export async function fetchHealth(): Promise<HealthStatus> {
  const base = getActiveApiBase();
  const data = await safeFetchJson<HealthStatus>(`${base}/health`);

  if (data && data.status) {
    return data;
  }

  // Fallback state when backend server is not connected
  return {
    status: 'demo_mode',
    service: 'CareSync (Demo Mode)',
    version: '0.1.0',
    ai: {
      provider: 'Google Gemini',
      model: 'gemini-3.5-flash',
      configured: false,
    },
  };
}

export async function fetchMetrics(): Promise<HospitalOperationalSnapshot> {
  const base = getActiveApiBase();
  const data = await safeFetchJson<HospitalOperationalSnapshot>(`${base}/metrics`);

  if (data && data.total_capacity_beds) {
    return data;
  }

  // Return realistic deterministic baseline snapshot
  return BASELINE_SNAPSHOT;
}

export async function fetchExplainInsights(
  bottleneckIds?: string[],
  focusArea?: string
): Promise<ExplainResponse> {
  const base = getActiveApiBase();
  const data = await safeFetchJson<ExplainResponse>(`${base}/insights/explain`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      bottleneck_ids: bottleneckIds && bottleneckIds.length > 0 ? bottleneckIds : null,
      focus_area: focusArea || null,
    }),
  });

  if (data && data.status) {
    return data;
  }

  // Graceful offline degradation without fabricating fake AI text
  const targetBottlenecks =
    bottleneckIds && bottleneckIds.length > 0
      ? BASELINE_SNAPSHOT.active_bottlenecks.filter((b) => bottleneckIds.includes(b.id))
      : BASELINE_SNAPSHOT.active_bottlenecks;

  return {
    status: 'model_unavailable',
    model_name: 'gemini-3.5-flash',
    verified_bottlenecks_analyzed: targetBottlenecks,
    explanations: [],
    error_message:
      'FastAPI backend is offline or unreachable from this static deployment. Connect your backend URL via "Settings" in the top bar to run live Google Gemini inference.',
    disclaimer:
      'CareSync operational recommendations are generated by AI from simulated operational metrics. They are intended solely for workflow review by hospital staff and do NOT constitute clinical diagnosis, medical advice, or clinical care decisions.',
  };
}

export interface SimulationParams {
  additional_general_med_nurses: number;
  additional_ed_nurses: number;
  restore_ct_scanner: boolean;
  expedited_discharges_count: number;
  stepdown_transfers_count: number;
}

export async function runSimulation(
  params: SimulationParams
): Promise<SimulationScenarioResult> {
  const base = getActiveApiBase();
  const data = await safeFetchJson<SimulationScenarioResult>(
    `${base}/simulation/simulate`,
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(params),
    }
  );

  if (data && data.scenario_description) {
    return data;
  }

  // Client-side simulation fallback if backend is offline
  return runClientSideSimulation(params);
}

/**
 * Deterministic simulation calculation on the client side when backend is offline.
 */
function runClientSideSimulation(params: SimulationParams): SimulationScenarioResult {
  const baseline = BASELINE_SNAPSHOT;
  const resolved: string[] = [];

  let simCtWait = 185.0;
  if (params.restore_ct_scanner) {
    simCtWait = 45.0;
    resolved.push('BN-DIAG-CT_SCAN');
  }

  let simGmRatio = 6.2;
  if (params.additional_general_med_nurses > 0) {
    const active = 18 + params.additional_general_med_nurses;
    const occupied = 112 - Math.min(params.expedited_discharges_count, 6);
    simGmRatio = Number((occupied / active).toFixed(1));
    if (simGmRatio <= 4.0) {
      resolved.push('BN-STAFF-GENERAL_MEDICINE');
    }
  }

  if (params.expedited_discharges_count >= 4) {
    resolved.push('BN-DISCHARGE-LAG');
  }

  let simIcuOcc = 95.8;
  if (params.stepdown_transfers_count > 0) {
    const occBeds = Math.max(0, 23 - params.stepdown_transfers_count);
    simIcuOcc = Number(((occBeds / 24) * 100).toFixed(1));
    if (simIcuOcc < 90.0) {
      resolved.push('BN-BED-INTENSIVE_CARE_UNIT');
    }
  }

  const remaining = baseline.active_bottlenecks.filter((b) => !resolved.includes(b.id));

  const descParts: string[] = [];
  if (params.restore_ct_scanner) descParts.push('CT Scanner restored');
  if (params.additional_general_med_nurses > 0) descParts.push(`+${params.additional_general_med_nurses} Gen Med RNs`);
  if (params.expedited_discharges_count > 0) descParts.push(`${params.expedited_discharges_count} discharges expedited`);
  if (params.stepdown_transfers_count > 0) descParts.push(`${params.stepdown_transfers_count} ICU stepdown transfers`);

  return {
    scenario_description: descParts.length > 0 ? descParts.join(', ') : 'Baseline parameters',
    baseline_bottleneck_count: baseline.active_bottlenecks.length,
    simulated_bottleneck_count: remaining.length,
    resolved_bottleneck_ids: resolved,
    remaining_bottlenecks: remaining,
    key_metric_comparisons: [
      {
        metric_name: 'CT Scanner Wait Time',
        unit: 'minutes',
        baseline_value: '185m',
        simulated_value: `${simCtWait}m`,
        change_direction: simCtWait < 185 ? 'improved' : 'unchanged',
        change_label: `${simCtWait - 185 >= 0 ? '+' : ''}${Math.round(simCtWait - 185)} min`,
      },
      {
        metric_name: 'Gen Med Nurse Ratio',
        unit: 'ratio',
        baseline_value: '6.2:1',
        simulated_value: `${simGmRatio}:1`,
        change_direction: simGmRatio < 6.2 ? 'improved' : 'unchanged',
        change_label: `${simGmRatio - 6.2 >= 0 ? '+' : ''}${(simGmRatio - 6.2).toFixed(1)} pts/RN`,
      },
      {
        metric_name: 'ICU Occupancy Rate',
        unit: 'percent',
        baseline_value: '95.8%',
        simulated_value: `${simIcuOcc}%`,
        change_direction: simIcuOcc < 95.8 ? 'improved' : 'unchanged',
        change_label: `${simIcuOcc - 95.8 >= 0 ? '+' : ''}${(simIcuOcc - 95.8).toFixed(1)}%`,
      },
      {
        metric_name: 'Active Bottlenecks',
        unit: 'count',
        baseline_value: baseline.active_bottlenecks.length,
        simulated_value: remaining.length,
        change_direction: remaining.length < baseline.active_bottlenecks.length ? 'improved' : 'unchanged',
        change_label: `${remaining.length - baseline.active_bottlenecks.length >= 0 ? '+' : ''}${remaining.length - baseline.active_bottlenecks.length} bottlenecks`,
      },
    ],
    departments: baseline.departments.map((d) => {
      if (d.department === 'Intensive Care Unit') {
        return {
          ...d,
          occupancy_rate_percent: simIcuOcc,
          status: simIcuOcc >= 90 ? 'critical' : simIcuOcc >= 85 ? 'warning' : 'normal',
        };
      }
      return d;
    }),
    diagnostics: baseline.diagnostic_backlogs.map((diag) => {
      if (diag.modality === 'CT Scan') {
        return {
          ...diag,
          average_wait_minutes: simCtWait,
          in_service_machines: params.restore_ct_scanner ? 3 : 2,
          status: simCtWait >= 90 ? 'critical' : 'normal',
        };
      }
      return diag;
    }),
    staffing: baseline.staffing_indicators.map((s) => {
      if (s.department === 'General Medicine') {
        return {
          ...s,
          patient_to_nurse_ratio: simGmRatio,
          active_nurses: 18 + params.additional_general_med_nurses,
          status: simGmRatio > 5.0 ? 'critical_shortage' : simGmRatio > 4.0 ? 'strained' : 'adequate',
        };
      }
      return s;
    }),
  };
}
