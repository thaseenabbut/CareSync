"""CareSync AI Insights Pydantic Schemas.

Strict request and response schemas for AI bottleneck explanation and action suggestions.
Ensures verified operational findings are passed in, and validated structured responses come out.
"""

from typing import Literal
from pydantic import BaseModel, Field
from schemas.hospital import BottleneckAlert


class ActionSuggestion(BaseModel):
    action: str = Field(description="Concrete operational step for hospital administrative/operational staff.")
    target_role: str = Field(description="Operational role, e.g. 'Discharge Planner', 'Charge Nurse', 'Transport Lead'.")
    urgency: Literal["immediate", "short_term", "next_shift"]
    expected_impact: str = Field(description="Anticipated operational relief or throughput improvement.")


class BottleneckExplanation(BaseModel):
    bottleneck_id: str
    operational_context: str = Field(description="Operational root cause analysis based on deterministic findings.")
    systemic_risk: str = Field(description="Operational risk to throughput or patient flow if left unaddressed.")
    suggested_actions: list[ActionSuggestion] = Field(default_factory=list)


class ExplainRequest(BaseModel):
    bottleneck_ids: list[str] | None = Field(
        default=None,
        description="Specific bottleneck IDs to explain. If omitted or empty, all active bottlenecks are analyzed."
    )
    focus_area: str | None = Field(
        default=None,
        description="Optional operational domain to focus on, e.g., 'bed_turnaround' or 'diagnostic_flow'."
    )


class ExplainResponse(BaseModel):
    status: Literal["success", "model_unavailable", "error"]
    model_name: str | None = None
    verified_bottlenecks_analyzed: list[BottleneckAlert] = Field(default_factory=list)
    explanations: list[BottleneckExplanation] = Field(default_factory=list)
    executive_summary: str | None = None
    error_message: str | None = None
    disclaimer: str = (
        "CareSync operational recommendations are generated by AI from simulated operational metrics. "
        "They are intended solely for workflow review by hospital staff and do NOT constitute clinical diagnosis, "
        "medical advice, or clinical care decisions."
    )
